def _assert_fragment(text, label):
    bare = _BARE_TRI.search(text)
    if bare:
        raise SystemExit(f"{PAGE} {label}: bare Tri-Cities")
    hit = _SUPER.search(text)
    if hit:
        raise SystemExit(f"{PAGE} {label}: do not use {hit.group(0)!r}")


def _assert_copy(page):
    visible = re.sub(r"<script[\s\S]*?</script>", " ", page)
    visible = re.sub(r"<[^>]+>", " ", visible)
    _assert_fragment(visible, "page")
    if "Axford Real Estate" not in page:
        raise SystemExit(f"{PAGE}: brokerage name missing")
    if "data-form-key=\"mortgageIntro\"" not in page:
        raise SystemExit(f"{PAGE}: intro form missing")
    if "Mortgage intro request" not in page:
        raise SystemExit(f"{PAGE}: form subject missing")
    if "mortgage licence" not in page and "mortgage license" not in page:
        raise SystemExit(f"{PAGE}: licence disclaimer missing")
    lowered = page.lower()
    if "not a mortgage broker" not in lowered:
        raise SystemExit(f"{PAGE}: broker disclaimer missing")
    if "illustrative only" not in lowered:
        raise SystemExit(f"{PAGE}: illustrative-only disclaimer missing")
    if "he is not a mortgage broker" not in lowered:
        raise SystemExit(f"{PAGE}: footer broker disclaimer missing")


def _check_payment():
    script = r'''
const t = require("./assets/js/mortgage-rates.js");
const payment = t.monthlyPayment(640000, 4.84, 25);
if (Math.abs(payment - 3664.19) > 0.02) throw new Error("payment " + payment);
if (t.monthlyPayment(0, 4.84, 25) !== null) throw new Error("zero principal");
if (Math.abs(t.monthlyPayment(640000, 0, 25) - (640000 / 300)) > 0.001) throw new Error("zero rate");
'''
    subprocess.run(["node", "-e", script], cwd=ROOT, check=True)


