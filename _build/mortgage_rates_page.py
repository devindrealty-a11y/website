def _term_pills(data):
    rows = []
    for index, term in enumerate(data["terms"]):
        checked = " checked" if term["id"] == "5y-fixed" else ""
        rows.append(
            f'<label class="rate-pill"><input type="radio" name="rate-term" value="{_esc(term["id"])}"{checked}>'
            f'<span>{_esc(term["label"])}</span></label>'
        )
    return "".join(rows)


def _bank_pills(data):
    rows = ['<label class="rate-pill"><input type="radio" name="rate-bank" value="all" checked><span>All banks</span></label>']
    for bank in data["banks"]:
        rows.append(
            f'<label class="rate-pill"><input type="radio" name="rate-bank" value="{_esc(bank["id"])}">'
            f'<span>{_esc(bank["name"])}</span></label>'
        )
    return "".join(rows)


def _cards(data):
    term = next(item for item in data["terms"] if item["id"] == "5y-fixed")
    cards = []
    for bank in data["banks"]:
        cell = bank["rates"][term["id"]]
        pressed = "true" if bank["id"] == "rbc" else "false"
        meta = cell.get("spread") or term["label"]
        cards.append(
            f'<button type="button" class="rate-card" data-bank-card="{_esc(bank["id"])}" aria-pressed="{pressed}">'
            f'<span class="rate-card-name">{_esc(bank["name"])}</span>'
            f'<span class="rate-card-legal">{_esc(bank["legalName"])}</span>'
            f'<span class="rate-card-rate"><span data-card-rate>{_rate(cell)}</span><span class="rate-unit">%</span></span>'
            f'<span class="rate-card-meta" data-card-meta>{_esc(meta)}</span>'
            f'</button>'
        )
    return "".join(cards)


def _static_table(data):
    heads = "".join(f"<th scope=\"col\">{_esc(term['label'])}</th>" for term in data["terms"])
    body = []
    for bank in data["banks"]:
        cells = []
        for term in data["terms"]:
            cell = bank["rates"][term["id"]]
            extra = f"<span>{_esc(cell['spread'])}</span>" if cell.get("spread") else ""
            cells.append(f"<td>{_rate(cell)}%{extra}</td>")
        body.append(f"<tr><th scope=\"row\">{_esc(bank['legalName'])}</th>{''.join(cells)}</tr>")
    return (
        f'<table class="rate-table"><caption>Illustrative only. Big 5 rates as of {_stamp(data["updatedLabel"])}. '
        f'Source: Ratehub.ca. Not a quote and not an approval.</caption>'
        f"<thead><tr><th scope=\"col\">Bank</th>{heads}</tr></thead><tbody>{''.join(body)}</tbody></table>"
    )


