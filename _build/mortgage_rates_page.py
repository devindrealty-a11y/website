def _esc(value):
    return html.escape(str(value), quote=True)


def _rate(cell):
    return f"{cell['rate']:.2f}"


def _stamp(label):
    return _esc(str(label).rstrip("."))


def _plain(fragment):
    text = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", text).strip()


